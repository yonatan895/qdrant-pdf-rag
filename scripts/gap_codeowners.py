#!/usr/bin/env python3
"""Generate and check the gap fork's GitLab CODEOWNERS (GH#1118 F4, ADR-0009 section 6).

The air-gapped GitLab fork has no Verifier, so GitLab code-owner approvals
stand in for it. This writes `.gitlab/CODEOWNERS` with two sections:

- `[Gap maintainers]`: every path except `gap/` is owned by the gap
  maintainer group. The site floor, GitLab 17.0, has no `!` exclusion, so each tracked
  top-level entry except `gap` gets its own line (and `.gitlab/` always): a
  new top-level path changes the output, so hygiene fails until the file,
  itself protected, is regenerated.
- `[Protected list]`: the Verifier's protected list also needs one of the
  named approvers, the gap's Verifier decision.

The protected list has one source of truth: the paths `scripts/acceptance.py`
binds as Verifier-owned (`VERIFICATION_INPUTS`, which includes
`scripts/unit_evidence.py` INPUTS, every `taskfiles/*.yml` and the producer
workflows), plus the gap's own gates in GAP_GATES. `tests/test_gap_codeowners.py`
pins that equality. The owner group and the approvers are arguments, so no
site name enters upstream; `refresh` and `check` read them back from the
committed file, whose bytes are themselves on the protected list.

Commands, from the checkout root (usage: ADR-0009 sections 4 and 6):
  write --group @GROUP --approver @USER [--approver @USER ...]
  refresh   rewrite the file for this checkout, keeping its owners
  check     the GitLab hygiene job: fail unless the committed file equals
            the generator output and no CODEOWNERS file shadows it

Exit codes: 0 ok, 1 check failed or refused, 2 usage. Messages are fixed.
Standard library only: the hygiene job runs it on the image's python3.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path

# absolute(), not resolve(): the checkout root is where the script is called
# from, even through a symlinked scripts/ (as tests/test_gap_codeowners.py runs it).
ROOT = Path(__file__).absolute().parents[1]
if __package__ in (None, ''):
    sys.path.insert(0, str(ROOT))  # direct script entry imports the Verifier's list as data

from scripts.acceptance import VERIFICATION_INPUTS
from scripts.acceptance_evidence import PRODUCERS

TARGET = '.gitlab/CODEOWNERS'
# GitLab reads the first of these that exists and ignores the rest, so either
# one would silently replace the generated file.
SHADOWING = ('CODEOWNERS', 'docs/CODEOWNERS')
# acceptance.verification_inputs binds every taskfiles/*.yml (one level); a
# GitLab `*` does not cross `/`, so this pattern is the same set and also
# covers a taskfile added after the file was generated.
TASKFILES = 'taskfiles/*.yml'
# The gap's own gates (ADR-0009 section 6). F6 adds the gap release pipeline
# and its signing files here when they exist; today's signers are the bundle
# and kit pack scripts. The generator is listed too: the hygiene job is only
# as strong as the check it runs.
GAP_GATES = (
    '.gitlab-ci.yml',
    TARGET,
    'scripts/check_junit_clean.py',
    'scripts/gate_l1.py',
    'scripts/tools/devkit-pin.txt',
    'scripts/airgap/pack.sh',
    'scripts/devkit/pack.sh',
    'scripts/gap_codeowners.py',
)
GROUP_SECTION = '[Gap maintainers]'
PROTECTED_SECTION = '[Protected list]'
UNOWNED = 'gap'
# A top-level name GitLab reads as a plain path: not a comment (#), exclusion
# (!), section ([, ^), glob or escape, and no whitespace.
NAME = re.compile(r'[A-Za-z0-9_.][A-Za-z0-9_.-]*')
HEADER = (
    '# Generated by scripts/gap_codeowners.py (ADR-0009 section 6). Do not edit by hand:',
    '# the GitLab hygiene job fails when this file differs from the generator output.',
    '# After an import, run: python3 scripts/gap_codeowners.py refresh',
)
# The group is a GitLab group path; each approver a single user handle, never
# a subgroup. Roles (`@@maintainer`), e-mail owners and whitespace are refused.
USER = r'@[A-Za-z0-9_][A-Za-z0-9_.-]*'
GROUP = re.compile(USER + r'(?:/[A-Za-z0-9_][A-Za-z0-9_.-]*)*')
APPROVER = re.compile(USER)
WRITE = '  python3 scripts/gap_codeowners.py write --group @GROUP --approver @USER\n'
DRIFT = ('FAIL: .gitlab/CODEOWNERS differs from the generator output (ADR-0009 section 6).\n'
         'Run: python3 scripts/gap_codeowners.py refresh, then commit the result in its own commit.\n'
         'If the file is missing or its owners are unreadable, write it with:\n' + WRITE)
# refresh keeps owners only when the file names them consistently; it never
# turns a hand-weakened line into the owners of every line.
UNREADABLE = ('FAIL: .gitlab/CODEOWNERS is missing, or does not name one group and one set of approvers\n'
              'on every entry, so refresh cannot keep its owners. Review it, then write it with:\n' + WRITE)
IO_ERROR = 'FAIL: .gitlab/CODEOWNERS or its directory cannot be read or written.\n'
GIT_ERROR = 'FAIL: git ls-files failed; run from a git checkout of the fork.\n'
NAME_ERROR = 'FAIL: a tracked top-level name cannot be a CODEOWNERS path; rename it.\n'
SHADOWED = ('FAIL: {path} exists, and GitLab would read it instead of .gitlab/CODEOWNERS.\n'
            'Remove it; .gitlab/CODEOWNERS is the only code-owner file (ADR-0009 section 6).\n')


class Refused(ValueError):
    """A fixed, user-facing refusal."""


def protected_paths() -> tuple[str, ...]:
    """The Verifier's protected list plus the gap's gates, sorted and unique."""
    workflows = {'.github/workflows/' + producer.workflow for producer in PRODUCERS}
    return tuple(sorted({*VERIFICATION_INPUTS, TASKFILES, *workflows, *GAP_GATES}))


def validate_owners(group: str, approvers: Sequence[str]) -> None:
    owners = [group, *approvers]
    if not (GROUP.fullmatch(group) and approvers and all(APPROVER.fullmatch(a) for a in approvers)):
        raise Refused('FAIL: give --group @group[/subgroup] and at least one --approver @user.\n')
    if len({owner.lower() for owner in owners}) != len(owners):
        raise Refused('FAIL: the group and the approvers must all be different.\n')


def group_owned(root: Path) -> tuple[str, ...]:
    """Each tracked top-level entry except gap/, as `name/` or `name`, plus `.gitlab/`."""
    try:
        listed = subprocess.run(['git', '-C', str(root), 'ls-files', '-z'], capture_output=True,
                                check=True, timeout=60).stdout
    except (OSError, subprocess.SubprocessError):
        raise Refused(GIT_ERROR) from None
    entries = {'.gitlab/'}
    for raw in filter(None, listed.split(b'\0')):
        path = raw.decode('utf-8', 'replace')
        name, nested, _ = path.partition('/')
        if not NAME.fullmatch(name):
            raise Refused(NAME_ERROR)
        if name != UNOWNED:
            entries.add(name + '/' if nested else name)
    return tuple(sorted(entries))


def render(root: Path, group: str, approvers: Sequence[str]) -> str:
    validate_owners(group, approvers)
    named = ' '.join(approvers)
    lines = [*HEADER, '', GROUP_SECTION, *(f'/{entry} {group}' for entry in group_owned(root)),
             '', PROTECTED_SECTION, *(f'/{path} {named}' for path in protected_paths())]
    return '\n'.join(lines) + '\n'


def owners_of(text: str) -> tuple[str, list[str]]:
    """The one group and the one approver set every entry of the file names."""
    lines = text.split('\n')
    try:
        start, middle = lines.index(GROUP_SECTION), lines.index(PROTECTED_SECTION)
    except ValueError:
        raise Refused(UNREADABLE) from None
    grouped, protected = lines[start + 1:middle - 1], lines[middle + 1:]
    if protected[-1:] == ['']:
        protected.pop()
    groups = {tuple(line.split(' ')[1:]) for line in grouped}
    named = {tuple(line.split(' ')[1:]) for line in protected}
    if len(groups) != 1 or len(named) != 1:
        raise Refused(UNREADABLE)
    group, approvers = groups.pop(), list(named.pop())
    if len(group) != 1:
        raise Refused(UNREADABLE)
    try:
        validate_owners(group[0], approvers)
    except Refused:
        raise Refused(UNREADABLE) from None
    return group[0], approvers


def committed_text(root: Path, refusal: str) -> tuple[bytes, str]:
    target = root / TARGET
    if target.is_symlink() or not target.is_file():
        raise Refused(refusal)
    committed = target.read_bytes()
    try:
        return committed, committed.decode('utf-8')
    except UnicodeDecodeError:
        raise Refused(refusal) from None


def check(root: Path) -> None:
    for path in SHADOWING:
        if (root / path).exists() or (root / path).is_symlink():
            raise Refused(SHADOWED.format(path=path))
    committed, text = committed_text(root, DRIFT)
    try:
        owners = owners_of(text)
    except Refused:
        raise Refused(DRIFT) from None
    if render(root, *owners).encode('utf-8') != committed:
        raise Refused(DRIFT)


def write(root: Path, group: str, approvers: Sequence[str]) -> None:
    text = render(root, group, approvers)
    target = root / TARGET
    if target.is_symlink():
        raise Refused('FAIL: .gitlab/CODEOWNERS is a symlink; replace it with a regular file.\n')
    target.parent.mkdir(exist_ok=True)
    target.write_text(text, encoding='utf-8', newline='\n')


def refresh(root: Path) -> None:
    write(root, *owners_of(committed_text(root, UNREADABLE)[1]))


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n', 1)[0])
    parser.add_argument('--root', type=Path, default=ROOT, help=argparse.SUPPRESS)
    commands = parser.add_subparsers(dest='command', required=True)
    write_parser = commands.add_parser('write', help='write .gitlab/CODEOWNERS for the given owners')
    write_parser.add_argument('--group', required=True, help='the gap maintainer group, @group')
    write_parser.add_argument('--approver', action='append', required=True,
                              help='a named approver for the protected list, @user (repeatable)')
    commands.add_parser('refresh', help='rewrite .gitlab/CODEOWNERS, keeping its owners')
    commands.add_parser('check', help='fail unless .gitlab/CODEOWNERS equals the generator output')
    args = parser.parse_args(argv)
    root: Path = args.root
    try:
        if args.command == 'write':
            write(root, args.group, args.approver)
        elif args.command == 'refresh':
            refresh(root)
        else:
            check(root)
            print('OK: .gitlab/CODEOWNERS equals the generator output.')
    except Refused as refusal:
        sys.stderr.write(str(refusal))
        return 1
    except OSError:
        sys.stderr.write(IO_ERROR)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
