def test_decode_only_prints_names_only_and_never_the_token(tmp_path, capsys):
    claims = {"roles": [BASELINE, GROUP], "upn": UPN, "name": DISPLAY, "aud": CLIENT_ID}
    token = make_jwt(claims)
    f = tmp_path / "id.jwt"
