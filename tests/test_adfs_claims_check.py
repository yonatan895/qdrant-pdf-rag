def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


def run_check(adfs: FakeAdfs, *extra: str, ca: str = "good-ca.pem", browse: bool = True):
    """Run the script as `python3 -I`, act as the browser, return (rc, output)."""
    secret = adfs.dir / "secret.txt"
    secret.write_text(SECRET + "\n")
    port = free_port()
    cmd = [
        sys.executable,
        "-I",
        str(SCRIPT),
        "--issuer",
        adfs.issuer,
        "--client-id",
        CLIENT_ID,
        "--client-secret-file",
        str(secret),
        "--ca-bundle",
        str(adfs.dir / ca),
        "--baseline-role",
        BASELINE,
        "--email-claim",
        "upn",
        "--port",
        str(port),
        "--redirect-host",
        "127.0.0.1",
        "--timeout",
        "20",
        *extra,
    ]
    proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    out_lines: list[str] = []
    try:
        if browse:
            ctx = ssl.create_default_context(cafile=str(adfs.dir / "good-ca.pem"))
            assert proc.stdout
            for line in proc.stdout:
                out_lines.append(line)
                if line.startswith("https://"):
                    browser_visit(line.strip(), ctx, port)
                    break
        rest, _ = proc.communicate(timeout=30)
    except Exception:
        proc.kill()
        raise
    return proc.returncode, "".join(out_lines) + rest


def browser_visit(url: str, ctx: ssl.SSLContext, port: int) -> None:
    class NoRedir(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *a: Any, **k: Any) -> None:  # type: ignore[override]
            return None

    opener = urllib.request.build_opener(urllib.request.HTTPSHandler(context=ctx), NoRedir)
    try:
        opener.open(url, timeout=10)
    except urllib.error.HTTPError as e:
        assert e.code == 302
        loc = e.headers["Location"]
    for _ in range(50):
        try:
            urllib.request.urlopen(loc, timeout=5).read()
            return
        except urllib.error.URLError:
            time.sleep(0.1)
    raise AssertionError("callback listener never came up")


