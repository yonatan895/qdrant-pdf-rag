def b64(obj: Any) -> str:
    return chk.b64url_nopad(json.dumps(obj).encode())


def make_jwt(claims: dict[str, Any]) -> str:
    return f"{b64({'alg': 'RS256'})}.{b64(claims)}.{chk.b64url_nopad(b'CANARY-SIGNATURE')}"


