needs_openssl = pytest.mark.skipif(
    shutil.which("openssl") is None, reason="openssl is not installed; cannot generate test CA"
)


def _openssl(*args: str, cwd: Path) -> None:
    subprocess.run(["openssl", *args], cwd=cwd, check=True, capture_output=True)


def make_ca(d: Path, name: str) -> None:
    _openssl(
        "req",
        "-x509",
        "-newkey",
        "rsa:2048",
        "-nodes",
        "-keyout",
        f"{name}-ca.key",
        "-out",
        f"{name}-ca.pem",
        "-days",
        "2",
        "-subj",
        f"/CN=test-{name}-ca",
        "-addext",
        "basicConstraints=critical,CA:TRUE",
        "-addext",
        "keyUsage=critical,keyCertSign,cRLSign",
        cwd=d,
    )


def make_server_cert(d: Path) -> None:
    (d / "ext.cnf").write_text("subjectAltName=IP:127.0.0.1,DNS:localhost\n")
    _openssl(
        "req",
        "-newkey",
        "rsa:2048",
        "-nodes",
        "-keyout",
        "srv.key",
        "-out",
        "srv.csr",
        "-subj",
        "/CN=localhost",
        cwd=d,
    )
    _openssl(
        "x509",
        "-req",
        "-in",
        "srv.csr",
        "-CA",
        "good-ca.pem",
        "-CAkey",
        "good-ca.key",
        "-CAcreateserial",
        "-out",
        "srv.pem",
        "-days",
        "2",
        "-extfile",
        "ext.cnf",
        cwd=d,
    )


class FakeAdfs:
    def __init__(self, d: Path) -> None:
        self.discovery_sleep = 0.0
        self.garbage_discovery = False
        self.claims_fn = lambda nonce: {
            "roles": [BASELINE, GROUP],
            "upn": UPN,
            "name": DISPLAY,
        }
        self.aud: Any = CLIENT_ID
        self.bad_state = False
        self.codes: dict[str, dict[str, str]] = {}
        self.token_requests: list[dict[str, str]] = []
        fake = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a: Any) -> None:
                pass

            def _send(
                self,
                code: int,
                body: bytes = b"",
                ctype: str = "application/json",
                loc: str | None = None,
            ) -> None:
                self.send_response(code)
                self.send_header("Content-Type", ctype)
                self.send_header("Content-Length", str(len(body)))
                if loc:
                    self.send_header("Location", loc)
                self.end_headers()
                self.wfile.write(body)

            def do_GET(self) -> None:
                u = urllib.parse.urlsplit(self.path)
                if u.path == "/adfs/.well-known/openid-configuration" and fake.garbage_discovery:
                    self.wfile.write(b"CANARY-GARBAGE not http\r\n\r\n")
                elif u.path == "/adfs/.well-known/openid-configuration":
                    time.sleep(fake.discovery_sleep)
                    self._send(
                        200,
                        json.dumps(
                            {
                                "issuer": fake.issuer,
                                "authorization_endpoint": fake.issuer + "/oauth2/authorize",
                                "token_endpoint": fake.issuer + "/oauth2/token",
                            }
                        ).encode(),
                    )
                elif u.path == "/adfs/oauth2/authorize":
                    q = {k: v[0] for k, v in urllib.parse.parse_qs(u.query).items()}
                    code = "code-" + q["nonce"][:6]
                    fake.codes[code] = q
                    state = "WRONG" if fake.bad_state else q["state"]
                    loc = (
                        q["redirect_uri"]
                        + "?"
                        + urllib.parse.urlencode({"code": code, "state": state})
                    )
                    self._send(302, loc=loc)
                else:
                    self._send(404)

            def do_POST(self) -> None:
                n = int(self.headers["Content-Length"])
                form = {
                    k: v[0] for k, v in urllib.parse.parse_qs(self.rfile.read(n).decode()).items()
                }
                fake.token_requests.append(form)
                req = fake.codes.get(form.get("code", ""))
                ok = req is not None and form.get("client_secret") == SECRET
                if ok:
                    digest = hashlib.sha256(form["code_verifier"].encode()).digest()
                    ok = chk.b64url_nopad(digest) == req["code_challenge"]
                if not ok:
                    self._send(400, b'{"error":"invalid_grant"}')
                    return
                claims = fake.claims_fn(req["nonce"]) | {
                    "iss": fake.issuer,
                    "aud": fake.aud,
                    "nonce": req["nonce"],
                    "exp": int(time.time()) + 600,
                }
                self._send(
                    200,
                    json.dumps(
                        {
                            "access_token": "CANARY-ACCESS-TOKEN",
                            "token_type": "bearer",
                            "id_token": make_jwt(claims),
                        }
                    ).encode(),
                )

        ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        ctx.load_cert_chain(d / "srv.pem", d / "srv.key")
        self.httpd = ThreadingHTTPServer(("127.0.0.1", 0), H)
        self.httpd.socket = ctx.wrap_socket(self.httpd.socket, server_side=True)
        self.issuer = f"https://127.0.0.1:{self.httpd.server_address[1]}/adfs"
        threading.Thread(target=self.httpd.serve_forever, daemon=True).start()


@pytest.fixture
def adfs(tmp_path: Path):
    make_ca(tmp_path, "good")
    make_ca(tmp_path, "other")
