def test_pkce_pair_is_s256():
    verifier, challenge = chk.pkce_pair()
    digest = hashlib.sha256(verifier.encode()).digest()
    assert challenge == base64.urlsafe_b64encode(digest).rstrip(b"=").decode()
    assert 43 <= len(verifier) <= 128


def test_authorize_url_carries_every_parameter():
    url = chk.build_authorize_url(
        "https://h/adfs/oauth2/authorize",
        "cid",
        "http://localhost:8400/callback",
        "openid profile email allatclaims",
        "st",
        "no",
        "ch",
    )
    q = urllib.parse.parse_qs(urllib.parse.urlsplit(url).query)
    assert q["scope"] == ["openid profile email allatclaims"]
    assert q["redirect_uri"] == ["http://localhost:8400/callback"]
    assert q["code_challenge_method"] == ["S256"]
    assert (q["state"], q["nonce"], q["code_challenge"]) == (["st"], ["no"], ["ch"])
    assert q["response_type"] == ["code"] and q["client_id"] == ["cid"]


def test_decode_jwt_payload_handles_padding_and_rejects_garbage():
    claims = {"a": "é", "b": [1]}
    assert chk.decode_jwt_payload(make_jwt(claims) + "\n") == claims
    for bad in ("", "a.b", "a.!!!.c", f"a.{chk.b64url_nopad(b'[1]')}.c"):
        with pytest.raises(chk.CheckError):
            chk.decode_jwt_payload(bad)


