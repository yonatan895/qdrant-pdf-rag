def test_validate_claims_each_check():
    now = 1000.0
    good = {"iss": "I", "aud": ["x", "C"], "nonce": "N", "exp": 2000}
    assert chk.validate_claims(good, issuer="I", client_id="C", nonce="N", now=now) == []
    for key, val in (("iss", "Z"), ("aud", "Z"), ("nonce", "Z"), ("exp", 999), ("exp", "9")):
        bad = good | {key: val}
        got = chk.validate_claims(bad, issuer="I", client_id="C", nonce="N", now=now)
        assert len(got) == 1 and got[0].startswith(key)
    assert chk.validate_claims({}, issuer=None, client_id=None, nonce=None, now=None) == []


def _analyse(claims, **kw):
    base = {
        "roles_claim": "roles",
        "email_claim": "upn",
        "username_claim": "name",
        "baseline": BASELINE,
        "expect_baseline_only": False,
    }
    return chk.analyse(claims, **(base | kw))


def test_analyse_reports_names_counts_and_no_values():
    claims = {"roles": [BASELINE, GROUP], "upn": UPN, "name": DISPLAY}
    lines, failures = _analyse(claims)
    text = "\n".join(lines)
    assert failures == []
    assert "type=list, count=2" in text and "baseline role present: yes" in text
    for canary in (GROUP, UPN, DISPLAY):
        assert canary not in text


def test_analyse_failures():
    assert "absent" in _analyse({"upn": UPN, "name": "n"})[1][0]
    assert "only the baseline" in _analyse({"roles": [BASELINE], "upn": UPN, "name": "n"})[1][0]
    assert (
        _analyse({"roles": [BASELINE], "upn": UPN, "name": "n"}, expect_baseline_only=True)[1] == []
    )
    assert "baseline role is missing" in _analyse({"roles": [GROUP], "upn": "u", "name": "n"})[1][0]
    assert "email claim" in _analyse({"roles": [BASELINE, GROUP], "name": "n"})[1][0]


